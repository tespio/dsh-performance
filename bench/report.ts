/**
 * Render the measured results into docs/results.md.
 *
 * Usage: node --experimental-transform-types bench/report.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const summary = JSON.parse(readFileSync(join(root, 'results', 'summary.json'), 'utf8'))

const MINUS = '\u2212'
const lines: string[] = []

function us(nanoseconds: number) {
  return (nanoseconds / 1000).toFixed(2)
}

lines.push('# Results', '')
lines.push(
  '![Before and after cost per operation](../charts/before-after.png)',
  '',
  'Generated by `bench/report.ts` from [`results/summary.json`](../results/summary.json). '
  + 'Medians with interquartile range over alternating in-process rounds.',
  '',
)
lines.push('| Case | Before (µs) | IQR | After (µs) | IQR | Speedup |')
lines.push('|---|---:|---:|---:|---:|---:|')
for (const entry of summary.cases) {
  lines.push(
    `| ${entry.label} | ${us(entry.base.median)} | ${us(entry.base.p25)}${MINUS}${us(entry.base.p75)} `
    + `| ${us(entry.patched.median)} | ${us(entry.patched.p25)}${MINUS}${us(entry.patched.p75)} `
    + `| **${entry.speedup.toFixed(2)}×** |`,
  )
}

lines.push('', '## Host', '')
const meta = summary.meta
lines.push(
  `- ${meta.cpu}, ${meta.cores} threads, ${meta.memoryGiB} GiB`,
  `- ${meta.platform}, Node ${String(meta.node).replace(/^v/, '')}`,
  `- ${meta.rounds} rounds per case, ${meta.scale === 1 ? 'full' : `${meta.scale * 100}%`} iterations`,
  `- \`new Error()\` costs ${us(meta.errorCostNs)} µs on this host; a plain object costs ${meta.objectCostNs.toFixed(1)} ns`,
  `- measured ${meta.startedAt}`,
  '',
)
lines.push(
  'The stack-capture cost is the lens for this table: rows that used to capture unused stacks '
  + 'improve most, and a host with cheaper `Error` construction would show smaller ratios for '
  + 'those rows even though the same work was removed.',
  '',
)

writeFileSync(join(root, 'docs', 'results.md'), `${lines.join('\n')}\n`)
console.log('wrote docs/results.md')
